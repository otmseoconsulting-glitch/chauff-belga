export function getFallbackCommuneBySlug(slug: string): CommuneRecord | null {
  const normalized = slug.toLowerCase().trim()
  return (
    FALLBACK_COMMUNES.find(
      (c) => c.slug_fr === normalized || c.slug_fr.replace(/-/g, '') === normalized
    ) || null
  )
}

/**
 * Real Haversine geographic proximity calculation
 * Returns true closest neighboring municipalities sorted by distance (km)
 */
export function getFallbackNearbyCommunes(
  currentId: string,
  limit = 8,
  targetSlug?: string,
  targetLat?: number,
  targetLng?: number
): NearbyCommuneResult[] {
  let current = FALLBACK_COMMUNES.find((c) => c.id === currentId)
  if (!current && targetSlug) {
    current = FALLBACK_COMMUNES.find((c) => c.slug_fr === targetSlug)
  }
  if (!current && targetLat !== undefined && targetLng !== undefined) {
    current = FALLBACK_COMMUNES.find(
      (c) => Math.abs(c.latitude - targetLat) < 0.05 && Math.abs(c.longitude - targetLng) < 0.05
    )
  }

  const lat = current ? current.latitude : (targetLat ?? 50.8503)
  const lng = current ? current.longitude : (targetLng ?? 4.3517)
  const currentSlug = current ? current.slug_fr : targetSlug

  return FALLBACK_COMMUNES.filter((c) => c.id !== currentId && c.slug_fr !== currentSlug)
    .map((c) => {
      const distance_km = calculateHaversineDistance(
        lat,
        lng,
        c.latitude,
        c.longitude
      )
      return {
        id: c.id,
        name_fr: c.name_fr,
        slug_fr: c.slug_fr,
        province_name_fr: c.provinces?.name_fr || 'Belgique',
        distance_km,
      }
    })
    .sort((a, b) => a.distance_km - b.distance_km)
    .slice(0, limit)
}

/**
 * Returns nearest Major City Authority Hub for Upward Link equity flow
 */
export function getFallbackNearestMajorHub(
  currentId: string,
  _provinceId?: string
): MajorCityResult | null {
  const current = FALLBACK_COMMUNES.find((c) => c.id === currentId)
  if (!current) return null

  // If already a major hub
  if (current.is_major_hub) {
    // If it's a regional hub other than Brussels city, it can still link up to Brussels if within 30km
    if (current.slug_fr !== 'bruxelles') {
      const bxl = FALLBACK_COMMUNES.find((c) => c.slug_fr === 'bruxelles')
      if (bxl) {
        const dist = calculateHaversineDistance(
          current.latitude,
          current.longitude,
          bxl.latitude,
          bxl.longitude
        )
        if (dist <= 35) {
          return {
            id: bxl.id,
            name_fr: bxl.name_fr,
            slug_fr: bxl.slug_fr,
            distance_km: dist,
          }
        }
      }
    }
    return null
  }

  // Find all major hubs, sort by actual physical distance
  const hubs = FALLBACK_COMMUNES.filter((c) => c.is_major_hub && c.id !== currentId)
  if (hubs.length === 0) return null

  const sortedHubs = hubs
    .map((h) => ({
      id: h.id,
      name_fr: h.name_fr,
      slug_fr: h.slug_fr,
      distance_km: calculateHaversineDistance(
        current.latitude,
        current.longitude,
        h.latitude,
        h.longitude
      ),
    }))
    .sort((a, b) => a.distance_km - b.distance_km)

  return sortedHubs[0] ?? null
}
